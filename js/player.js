// ============================================================


export class Player {

    constructor(x, y) {

        // ----------------------------------------------------
        // 위치
        // ----------------------------------------------------

        this.x = x;
        this.y = y;


        // ----------------------------------------------------
        // 크기
        // ----------------------------------------------------

        this.radius = 14;


        // ----------------------------------------------------
        // 이동 속도
        // ----------------------------------------------------

        this.speed = 280;


        // ----------------------------------------------------
        // 체력
        // ----------------------------------------------------

        // 목숨은 딱 1개

        this.maxHealth = 1;

        this.health = 1;


        // ----------------------------------------------------
        // 피격 효과
        // ----------------------------------------------------

        this.hitTimer = 0;

    }


    // ========================================================
    // 초기화
    // ========================================================

    reset(x, y) {

        this.x = x;
        this.y = y;

        this.health = 1;

        this.hitTimer = 0;

    }


    // ========================================================
    // 업데이트
    // ========================================================

    update(
        delta,
        keys,
        width,
        height
    ) {

        let dx = 0;
        let dy = 0;


        // ----------------------------------------------------
        // 방향키
        // ----------------------------------------------------

        if (keys["ArrowUp"]) {

            dy -= 1;

        }


        if (keys["ArrowDown"]) {

            dy += 1;

        }


        if (keys["ArrowLeft"]) {

            dx -= 1;

        }


        if (keys["ArrowRight"]) {

            dx += 1;

        }


        // ----------------------------------------------------
        // 대각선 속도 보정
        // ----------------------------------------------------

        const length =
            Math.sqrt(
                dx * dx +
                dy * dy
            );


        if (length > 0) {

            dx /= length;
            dy /= length;

        }


        // ----------------------------------------------------
        // 이동
        // ----------------------------------------------------

        this.x +=
            dx *
            this.speed *
            delta;


        this.y +=
            dy *
            this.speed *
            delta;


        // ----------------------------------------------------
        // 화면 밖으로 나가지 못하게
        // ----------------------------------------------------

        this.x =
            Math.max(
                this.radius,
                Math.min(
                    width - this.radius,
                    this.x
                )
            );


        this.y =
            Math.max(
                this.radius,
                Math.min(
                    height - this.radius,
                    this.y
                )
            );


        // ----------------------------------------------------
        // 피격 효과 시간
        // ----------------------------------------------------

        if (
            this.hitTimer > 0
        ) {

            this.hitTimer -= delta;

        }

    }


    // ========================================================
    // 피해 받기
    // ========================================================

    takeDamage() {

        // 이미 죽었다면 무시

        if (
            this.health <= 0
        ) {

            return;

        }


        // 목숨 1개 → 바로 사망

        this.health = 0;


        // 피격 효과

        this.hitTimer = 0.25;

    }


    // ========================================================
    // 플레이어 그리기
    // ========================================================

    draw(ctx) {

        // 죽었다면 그리지 않음

        if (
            this.health <= 0
        ) {

            return;

        }


        const x = this.x;
        const y = this.y;


        // ----------------------------------------------------
        // 피격 시 빨간색
        // ----------------------------------------------------

        const hit =
            this.hitTimer > 0;


        ctx.save();


        // ====================================================
        // 그림자
        // ====================================================

        ctx.fillStyle =
            "rgba(0, 0, 0, 0.45)";


        ctx.beginPath();

        ctx.ellipse(
            x,
            y + 18,
            20,
            7,
            0,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ====================================================
        // 외곽 광
        // ====================================================

        ctx.shadowColor =
            hit
                ? "rgba(255, 70, 60, 0.8)"
                : "rgba(225, 190, 80, 0.5)";


        ctx.shadowBlur =
            hit ? 20 : 12;


        // ====================================================
        // 몸
        // ====================================================

        ctx.fillStyle =
            hit
                ? "#9b3838"
                : "#496b43";


        ctx.beginPath();

        ctx.ellipse(
            x,
            y + 7,
            13,
            16,
            0,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ====================================================
        // 얼굴
        // ====================================================

        ctx.shadowBlur = 0;

        ctx.fillStyle =
            "#d9ad78";


        ctx.beginPath();

        ctx.arc(
            x,
            y - 6,
            9,
            0,
            Math.PI * 2
        );

        ctx.fill();


        // ====================================================
        // 삿갓
        // ====================================================

        ctx.fillStyle =
            "#735a32";


        ctx.beginPath();

        ctx.moveTo(
            x,
            y - 28
        );

        ctx.lineTo(
            x - 22,
            y - 7
        );

        ctx.lineTo(
            x + 22,
            y - 7
        );

        ctx.closePath();

        ctx.fill();


        // 삿갓 테두리

        ctx.strokeStyle =
            "#302412";

        ctx.lineWidth = 2;

        ctx.stroke();


        // ====================================================
        // 눈
        // ====================================================

        ctx.fillStyle =
            "#17130c";


        ctx.fillRect(
            x - 4,
            y - 6,
            2,
            2
        );


        ctx.fillRect(
            x + 2,
            y - 6,
            2,
            2
        );


        // ====================================================
        // 허리띠
        // ====================================================

        ctx.strokeStyle =
            "#c3a34f";

        ctx.lineWidth = 2;


        ctx.beginPath();

        ctx.moveTo(
            x - 9,
            y + 8
        );

        ctx.lineTo(
            x + 9,
            y + 8
        );

        ctx.stroke();


        ctx.restore();

    }

}
